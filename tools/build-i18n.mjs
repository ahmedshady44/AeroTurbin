// Optional helper. Builds i18n/bundle.js from the JSON files so the site also works when
// index.html is opened straight from disk (browsers block fetch() on file:// pages).
// Usage:  node tools/build-i18n.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'i18n');
const out = {};
for (const f of readdirSync(dir).filter((n) => n.endsWith('.json'))) {
  out[f.replace('.json', '')] = JSON.parse(readFileSync(join(dir, f), 'utf8'));
}
writeFileSync(join(dir, 'bundle.js'), '/* Generated by tools/build-i18n.mjs. Do not edit. */\nwindow.AERO_I18N = ' + JSON.stringify(out) + ';\n');
console.log('Wrote i18n/bundle.js with: ' + Object.keys(out).join(', '));
